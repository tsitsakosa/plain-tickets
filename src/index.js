const START = '<!-- plain-tickets:start -->'
const END = '<!-- plain-tickets:end -->'

// Puts the guide between markers in AGENTS.md: replaces an existing block in place, else appends one.
// Text outside the markers is kept byte for byte.
export function upsertBlock(text, block) {
  const wrapped = `${START}\n${block.trimEnd()}\n${END}`
  const start = text.indexOf(START)
  const end = text.indexOf(END)
  if (start === -1 && end === -1) return text ? `${text.replace(/\n*$/, '\n\n')}${wrapped}\n` : `${wrapped}\n`
  if (start === -1 || end < start) throw new Error(`found ${start === -1 ? END : START} without its pair`)
  return text.slice(0, start) + wrapped + text.slice(end + END.length)
}
