// Reads markdown tickets with YAML frontmatter, validates them strictly and renders a markdown board.
// No side effects on import: the CLI in bin/ does the reading of config and the writing of the board.
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'

export const TYPES = ['epic', 'feature', 'bug', 'chore', 'idea']
// Board order: work in flight first, finished work last.
export const STATUSES = ['in-progress', 'review', 'todo', 'backlog', 'done', 'wontfix']
export const PRIORITIES = ['P1', 'P2', 'P3', 'P4']
const FIELDS = ['id', 'title', 'type', 'status', 'priority', 'epic', 'refs', 'commits']
const DATES = ['created', 'updated']
const DATE = /^\d{4}-\d{2}-\d{2}$/

export const DEFAULT_CONFIG = {
  prefix: 'T',
  dir: 'tickets',
  board: 'tickets/BOARD.md',
  labels: {
    title: 'Tickets',
    intro: 'Generated by `plain-tickets board` from the ticket frontmatter. Do not edit by hand.',
    status: 'Status',
    total: 'Total',
    epics: 'Epics',
    noEpic: 'No epic',
    empty: '_No tickets._',
  },
}

// Loads tickets.config.json (or the given file) and resolves paths against the config's folder.
// Without a config file every default applies and paths resolve against cwd.
export function loadConfig(cwd, configPath) {
  const file = resolve(cwd, configPath ?? 'tickets.config.json')
  if (!existsSync(file)) {
    if (configPath) throw new Error(`config file ${configPath} does not exist`)
    return resolveConfig(DEFAULT_CONFIG, cwd)
  }
  let raw
  try {
    raw = JSON.parse(readFileSync(file, 'utf8'))
  } catch (error) {
    throw new Error(`${relative(cwd, file)} is not valid JSON: ${error.message}`)
  }
  const errors = checkConfig(raw)
  if (errors.length) throw new Error(`${relative(cwd, file)}: ${errors.join('; ')}`)
  const config = { ...DEFAULT_CONFIG, ...raw, labels: { ...DEFAULT_CONFIG.labels, ...raw.labels } }
  return resolveConfig(config, dirname(file))
}

function checkConfig(raw) {
  if (raw === null || typeof raw !== 'object' || Array.isArray(raw)) return ['must be a JSON object']
  const errors = []
  for (const key of Object.keys(raw)) {
    if (!(key in DEFAULT_CONFIG)) errors.push(`unknown key "${key}"`)
  }
  if ('prefix' in raw && !/^[A-Z][A-Z0-9]*$/.test(raw.prefix)) {
    errors.push('prefix must be capital letters and digits, starting with a letter, like "T" or "WEB"')
  }
  for (const key of ['dir', 'board']) {
    if (key in raw && (typeof raw[key] !== 'string' || raw[key] === '')) errors.push(`${key} must be a path`)
  }
  if ('board' in raw && typeof raw.board === 'string' && !raw.board.endsWith('.md')) {
    errors.push('board must end with .md')
  }
  if ('labels' in raw) {
    if (raw.labels === null || typeof raw.labels !== 'object' || Array.isArray(raw.labels)) {
      errors.push('labels must be an object')
    } else {
      for (const [key, value] of Object.entries(raw.labels)) {
        if (!(key in DEFAULT_CONFIG.labels)) errors.push(`unknown label "${key}"`)
        else if (typeof value !== 'string') errors.push(`label "${key}" must be a string`)
      }
    }
  }
  return errors
}

function resolveConfig(config, base) {
  return { ...config, dir: resolve(base, config.dir), board: resolve(base, config.board) }
}

// The frontmatter is a small YAML subset: `key: value`, `key: null`, `key: []`,
// and a list as `key:` followed by `  - item` lines. Values may be double- or single-quoted.
function scalar(raw) {
  if (raw.startsWith('"')) return JSON.parse(raw)
  if (raw.startsWith("'")) {
    if (raw.length < 2 || !raw.endsWith("'")) throw new Error(`unclosed quote in ${raw}`)
    return raw.slice(1, -1).replaceAll("''", "'")
  }
  return raw
}

export function parseFrontmatter(text) {
  const lines = text.split(/\r?\n/)
  if (lines[0] !== '---') throw new Error('no frontmatter: the file must start with a --- line')
  const end = lines.indexOf('---', 1)
  if (end === -1) throw new Error('the frontmatter has no closing --- line')
  const data = {}
  let list = null
  for (const [index, line] of lines.slice(1, end).entries()) {
    const item = /^ {2}- (.+)$/.exec(line)
    if (item && list) {
      list.push(scalar(item[1].trim()))
      continue
    }
    const pair = /^([a-z]+):(?: (.*))?$/.exec(line)
    if (!pair) throw new Error(`frontmatter line ${index + 2} is not "key: value" or "  - item"`)
    const [, key, raw = ''] = pair
    if (key in data) throw new Error(`"${key}" appears twice`)
    const value = raw.trim()
    list = null
    if (value === '') data[key] = list = []
    else if (value === '[]') data[key] = []
    else if (value === 'null') data[key] = null
    else data[key] = scalar(value)
  }
  return data
}

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const idPattern = (prefix) => new RegExp(`^${escapeRegExp(prefix)}-\\d{4}$`)
const fileNamePattern = (prefix) =>
  new RegExp(`^(${escapeRegExp(prefix)}-\\d{4})-[a-z0-9]+(?:-[a-z0-9]+)*\\.md$`)

// Checks one ticket on its own. Returns a list of problems, empty when the ticket is valid.
export function validate(ticket, idFromName, prefix) {
  const known = [...FIELDS, ...DATES]
  const missing = known.filter((key) => !(key in ticket)).map((key) => `missing "${key}"`)
  const unknown = Object.keys(ticket)
    .filter((key) => !known.includes(key))
    .map((key) => `unknown field "${key}"`)
  if (missing.length || unknown.length) return [...missing, ...unknown]

  const errors = []
  const oneOf = (key, allowed) => {
    if (!allowed.includes(ticket[key])) {
      errors.push(`${key} "${ticket[key]}" is not one of ${allowed.join(', ')}`)
    }
  }
  if (ticket.id !== idFromName) errors.push(`id "${ticket.id}" does not match the file name`)
  if (typeof ticket.title !== 'string' || ticket.title === '') errors.push('title is empty')
  oneOf('type', TYPES)
  oneOf('status', STATUSES)
  oneOf('priority', PRIORITIES)
  if (ticket.epic !== null && !idPattern(prefix).test(ticket.epic)) {
    errors.push(`epic must be null or a ticket id, not "${ticket.epic}"`)
  }
  for (const key of ['refs', 'commits']) {
    if (!Array.isArray(ticket[key])) errors.push(`${key} must be a list`)
  }
  const badDates = DATES.filter((key) => !DATE.test(ticket[key]))
  errors.push(...badDates.map((key) => `${key} must be a YYYY-MM-DD date`))
  if (!badDates.length && ticket.updated < ticket.created) errors.push('updated is before created')
  return errors
}

// Reads every ticket in config.dir. Problems name the file (relative to cwd) and the reason.
export function readTickets(config, cwd = process.cwd()) {
  const problems = []
  const tickets = []
  const show = (file) => relative(cwd, join(config.dir, file)).split(sep).join('/')
  if (!existsSync(config.dir)) {
    return { tickets, byId: new Map(), problems: [`tickets folder ${relative(cwd, config.dir) || '.'} does not exist`] }
  }
  const fileName = fileNamePattern(config.prefix)
  const files = readdirSync(config.dir)
    .filter((name) => name.endsWith('.md') && name !== 'README.md')
    .filter((name) => join(config.dir, name) !== config.board)
    .sort()
  for (const file of files) {
    const name = fileName.exec(file)
    if (!name) {
      problems.push(`${show(file)}: the file name must be ${config.prefix}-####-short-slug.md`)
      continue
    }
    try {
      const ticket = parseFrontmatter(readFileSync(join(config.dir, file), 'utf8'))
      const errors = validate(ticket, name[1], config.prefix)
      if (errors.length) problems.push(...errors.map((error) => `${show(file)}: ${error}`))
      else tickets.push({ ...ticket, file })
    } catch (error) {
      problems.push(`${show(file)}: ${error.message}`)
    }
  }

  const byId = new Map()
  for (const ticket of tickets) {
    const other = byId.get(ticket.id)
    if (other) problems.push(`${show(ticket.file)}: id also used by ${other.file}`)
    byId.set(ticket.id, ticket)
  }
  for (const ticket of tickets) {
    if (ticket.epic === null) continue
    const epic = byId.get(ticket.epic)
    if (ticket.type === 'epic') problems.push(`${show(ticket.file)}: an epic cannot belong to an epic`)
    else if (!epic) problems.push(`${show(ticket.file)}: epic ${ticket.epic} does not exist`)
    else if (epic.type !== 'epic') problems.push(`${show(ticket.file)}: ${ticket.epic} is not an epic`)
  }
  return { tickets, byId, problems }
}

const byPriorityThenId = (a, b) => a.priority.localeCompare(b.priority) || a.id.localeCompare(b.id)

// Renders the board markdown. Ticket links are relative to the board's own folder.
export function renderBoard(tickets, byId, config) {
  const { labels } = config
  const link = (ticket) =>
    encodeURI(relative(dirname(config.board), join(config.dir, ticket.file)).split(sep).join('/'))
  const line = (ticket) =>
    `- [${ticket.id}](${link(ticket)}) ${ticket.priority} · ${ticket.type} · ${ticket.title}`

  const count = (status, type) =>
    tickets.filter((t) => (!status || t.status === status) && (!type || t.type === type)).length
  const row = (label, status) =>
    `| ${label} | ${[...TYPES.map((type) => count(status, type)), count(status)].join(' | ')} |`
  const table = [
    `| ${labels.status} | ${TYPES.join(' | ')} | ${labels.total} |`,
    `| --- | ${TYPES.map(() => '---:').join(' | ')} | ---: |`,
    ...STATUSES.map((status) => row(status, status)),
    row(`**${labels.total}**`, null),
  ]

  const section = (status) => {
    const inStatus = tickets.filter((ticket) => ticket.status === status)
    const out = ['', `## ${status} (${inStatus.length})`]
    if (!inStatus.length) return [...out, '', labels.empty]

    const epics = inStatus.filter((ticket) => ticket.type === 'epic').sort(byPriorityThenId)
    if (epics.length) out.push('', `### ${labels.epics}`, '', ...epics.map(line))

    const children = inStatus.filter((ticket) => ticket.type !== 'epic')
    const epicIds = [...new Set(children.map((ticket) => ticket.epic))]
    const groups = epicIds.filter((id) => id !== null).sort()
    if (epicIds.includes(null)) groups.push(null)
    for (const id of groups) {
      const epic = byId.get(id)
      out.push('', id === null ? `### ${labels.noEpic}` : `### [${epic.id}](${link(epic)}) ${epic.title}`)
      out.push('', ...children.filter((ticket) => ticket.epic === id).sort(byPriorityThenId).map(line))
    }
    return out
  }

  const intro = labels.intro ? ['', labels.intro] : []
  return [`# ${labels.title}`, ...intro, '', ...table, ...STATUSES.flatMap(section), ''].join('\n')
}
